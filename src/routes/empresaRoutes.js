import { Router } from "express";
import * as E from "../controllers/EmpresaController.js";
import * as R from "../controllers/RepresentanteController.js";
import { exigirLogin } from "../middlewares/autenticacao.js";

const router = Router();
router.use(exigirLogin(["empresa"]));
router.get("/perfil", E.perfil);
router.put("/perfil", E.atualizarPerfil);
router.get("/verificacao", R.ver);
router.post("/verificacao", R.verificar);
router.get("/vagas", E.listarVagas);
router.post("/vagas", E.criarVaga);
router.get("/vagas/:id", E.verVaga);
router.put("/vagas/:id", E.editarVaga);
router.patch("/vagas/:id/status", E.mudarStatusVaga);
router.delete("/vagas/:id", E.excluirVaga);
router.get("/dashboard", E.dashboard);
router.get("/candidaturas", E.listarCandidaturas);
router.get("/candidaturas/:id", E.verCandidatura);
router.get("/candidaturas/:id/curriculo", E.baixarCurriculoCandidatura);
router.patch("/candidaturas/:id/status", E.mudarStatusCandidatura);
router.get("/publicacoes", E.listarPublicacoes);
router.post("/publicacoes", E.criarPublicacao);
router.put("/publicacoes/:id", E.editarPublicacao);
router.delete("/publicacoes/:id", E.excluirPublicacao);
router.get("/feed", E.feed);
router.get("/talentos", E.talentos);
router.get("/talentos/:id", E.talento);
router.post("/talentos/:id/convites", E.convidar);

export default router;
